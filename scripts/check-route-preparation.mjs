import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const root=fileURLToPath(new URL('../',import.meta.url));
mkdirSync(join(root,'validation'),{recursive:true});
const fixture=mkdtempSync(join(root,'validation','routes-'));
for(const dir of ['scripts','config','content','app/_routes'])mkdirSync(join(fixture,dir),{recursive:true});
for(const file of ['prepare-routes.mjs','load-site-config.mjs'])copyFileSync(join(root,'scripts',file),join(fixture,'scripts',file));
copyFileSync(join(root,'app/_routes/localized-page.tsx'),join(fixture,'app/_routes/localized-page.tsx'));
const template=join(fixture,'app/_routes/localized-page.tsx');
const active=join(fixture,'app/[locale]/[[...path]]/page.tsx');
const config=locales=>writeFileSync(join(fixture,'config/site.ts'),`export const siteConfig = { publishedLocales: ${JSON.stringify(locales)} };`);
writeFileSync(join(fixture,'content/pages.json'),JSON.stringify([{publicationStatus:'published',localeAvailability:['en','de']} ]));
const run=()=>spawnSync(process.execPath,['scripts/prepare-routes.mjs'],{cwd:fixture,encoding:'utf8'});
config(['en']);assert.equal(run().status,0);assert.equal(existsSync(active),false);
config(['en','de']);assert.equal(run().status,0);assert.ok(existsSync(active));
writeFileSync(template,readFileSync(template,'utf8')+'\n// Fixture template update\n');
assert.equal(run().status,0,'A legitimate source template update must regenerate');assert.match(readFileSync(active,'utf8'),/Fixture template update/);
const generated=readFileSync(active,'utf8');writeFileSync(active,generated+'\n// Custom edit\n');
assert.notEqual(run().status,0,'Unrecognized edits must be protected');assert.match(readFileSync(active,'utf8'),/Custom edit/);
writeFileSync(active,'export default function CustomRoute() { return null; }');
assert.notEqual(run().status,0,'An unmarked custom route must be protected');assert.match(readFileSync(active,'utf8'),/CustomRoute/);
writeFileSync(active,generated);mkdirSync(join(fixture,'.next/types'),{recursive:true});writeFileSync(join(fixture,'.next/types/stale.ts'),'stale generated type');
config(['en']);assert.equal(run().status,0);assert.equal(existsSync(active),false);assert.equal(existsSync(join(fixture,'.next')),false);
console.log(`Route regression passed: English, real second locale, template update, custom protection, stale cache archival. Evidence: ${fixture}`);
