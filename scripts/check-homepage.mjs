import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const data = JSON.parse(read("config/homepage.json"));
const pages = JSON.parse(read("content/pages.json"));
const home = pages.find(page => page.page_id === "home");
const html = read("out/index.html");
const escape = value => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("'", "&#x27;");
assert.equal(data.home.meta.title, data.metadata.title);
assert.equal(data.home.meta.description, data.metadata.description);
assert.equal(home.title.en, data.metadata.title);
assert.equal(home.description.en, data.metadata.description);
assert.ok(data.metadata.title.length <= 60);
assert.ok(data.metadata.description.length >= 140 && data.metadata.description.length <= 160);
assert.ok(data.metadata.keywords.length <= 100);
assert.equal(data.home.start.cards.length, 4);
assert.equal(data.home.start.cards[0].title, "Beginner Guide");
assert.equal(new Set(data.home.start.cards.map(card => card.href)).size, 4);
assert.equal(data.home.hero.stats.length, 4);
assert.ok(data.home.hero.stats.every(stat => typeof stat === "string" && !/[()]/.test(stat)));
assert.equal(data.home.aboutGame.paragraphs.length, 2);
assert.equal(data.home.aboutGame.stats.length, 4);
assert.ok(data.home.aboutGame.stats.every(stat => stat.value && !/[()]/.test(stat.value)));
assert.ok(data.sidebarCodes.length <= 2);
assert.equal((html.match(/data-start-card=/g) ?? []).length, 4);
assert.equal((html.match(/<h1\b/g) ?? []).length, 1);
assert.ok(html.includes(`<h1>${data.home.hero.title}</h1>`));
assert.ok(html.includes(`<title>${escape(data.metadata.title)}</title>`));
assert.ok(html.includes(`property="og:title" content="${escape(data.metadata.title)}"`));
assert.ok(html.includes(`name="description" content="${escape(data.metadata.description)}"`));
assert.ok(html.includes(`property="og:description" content="${escape(data.metadata.description)}"`));
for (const value of [...data.home.hero.stats, ...data.home.aboutGame.paragraphs, data.footer.about]) assert.ok(html.includes(escape(value)), `Unrendered homepage field: ${value}`);
for (const code of data.sidebarCodes) assert.ok(html.includes(code.code));
for (const anchor of ["privacy-policy", "terms-of-service"]) assert.ok(read("out/sources/index.html").includes(`id="${anchor}"`));
assert.ok(!html.includes("Official trailer"));
assert.ok(html.includes(data.home.hero.videoLabel));
console.log(`Homepage requirements passed: rendered title ${data.metadata.title.length}, description ${data.metadata.description.length}, keywords ${data.metadata.keywords.length}; four cards, four stats, complete mapped content and working policy anchors.`);
