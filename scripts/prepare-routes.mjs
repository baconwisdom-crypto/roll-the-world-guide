import { readFileSync, writeFileSync, existsSync, mkdirSync, unlinkSync, renameSync } from 'node:fs';
import { loadSiteConfig } from './load-site-config.mjs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const config = await loadSiteConfig(root);
const pages = JSON.parse(readFileSync(new URL('content/pages.json', root), 'utf8'));
const localized = pages.some(p => p.publicationStatus === 'published' && p.localeAvailability.some(l => l !== 'en' && config.publishedLocales.includes(l)));
const target = new URL('app/[locale]/[[...path]]/page.tsx', root);
const template = readFileSync(new URL('app/_routes/localized-page.tsx', root), 'utf8').replaceAll('\r\n','\n');
const hash = source => createHash('sha256').update(source).digest('hex');
const generated = `// Generated by prepare:routes; sha256=${hash(template)}. Edit app/_routes/localized-page.tsx.\n` + template;
const previous = existsSync(target) ? readFileSync(target, 'utf8').replaceAll('\r\n','\n') : null;
// An existing unrecognized file is preserved and requires deliberate migration.
const previousHash = previous?.match(/^\/\/ Generated by prepare:routes; sha256=([a-f0-9]{64})\./)?.[1];
const trustedGenerated = previousHash && hash(previous.slice(previous.indexOf('\n')+1)) === previousHash;
const oldGenerated = '// Generated by prepare:routes. Edit app/_routes/localized-page.tsx.\n' + template;
if (previous !== null && previous !== template && previous !== oldGenerated && !trustedGenerated) throw new Error('Localized route has custom changes. Move them into app/_routes/localized-page.tsx before preparing routes.');
const changed = localized ? previous !== generated : previous !== null;
if (localized) { mkdirSync(new URL('app/[locale]/[[...path]]/', root), { recursive: true }); if (changed) writeFileSync(target, generated); }
else if (previous !== null) unlinkSync(target);
if (changed && existsSync(new URL('.next/', root))) {
  // Route topology changed. Archive generated types/cache instead of suppressing errors.
  const archive = new URL(`research/generated-cache-${Date.now()}/`, root);
  mkdirSync(new URL('research/', root), { recursive: true });
  renameSync(new URL('.next/', root), archive);
}
console.log(`Prepared locale route: ${localized ? 'enabled' : 'not needed'}; no synthetic URLs.`);
